"""Write an INDEX.md of Harbor trials: one row per trial, linking everything a reviewer opens.

    python -I index.py JOB_OR_JOBS_DIR [MORE ...] [--out spikes/keyless/runs/INDEX.md]
                       [--incidents INCIDENTS.md] [--viewer http://127.0.0.1:8080]

Per trial: reward, product, honesty, first failed AT step, and links to the agent log (opencode.txt or
codex.txt), the ATIF trajectory, the agent's report.json, the score breakdown (verifier/details.json),
the grader log, up to three images the agent made under /app, the incident record if there is one, and
the trial's page in Harbor's viewer (`harbor view JOBS_DIR`, routes /jobs/<job>/trials/<trial>).

Links are relative to the INDEX.md's folder, so the page works on GitHub when the job dirs (or the
collected copies, as in spikes/right_angle/runs/) sit in the repo, and locally otherwise. The default
output, spikes/keyless/runs/INDEX.md, follows the repo's runs/ convention (spikes/<spike>/runs/).
"""
import argparse
import os
import sys
from collections import OrderedDict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import harbor_io as H  # noqa: E402


def link(text, target, base):
    if not target:
        return "–"
    rel = os.path.relpath(target, base).replace(os.sep, "/").replace(" ", "%20")
    return "[%s](%s)" % (text, rel)


def num(x):
    return "–" if x is None else ("%.3f" % x if isinstance(x, float) else str(x))


def anchor(trial_name):
    return "inc-" + "".join(c.lower() if c.isalnum() else "-" for c in trial_name)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("paths", nargs="+")
    ap.add_argument("--out", default="INDEX.md")
    ap.add_argument("--incidents", help="INCIDENTS.md written by incidents.py, to link each record")
    ap.add_argument("--viewer", default="http://127.0.0.1:8080", help="base URL of `harbor view`")
    ap.add_argument("--title", default="Keyless works: trial index")
    a = ap.parse_args(argv)
    out = os.path.abspath(a.out)
    base = os.path.dirname(out)
    os.makedirs(base, exist_ok=True)
    trials = H.load_trials(a.paths)
    if not trials:
        sys.exit("no Harbor trials found under: " + ", ".join(a.paths))
    order = {"oracle": 0, "nop": 1}
    trials.sort(key=lambda t: (order.get(t["group"], 2), t["group"], t["started_at"] or "", t["trial_name"]))
    recorded = set()
    if a.incidents:                      # link only the trials incidents.py actually wrote a record for
        recs = H.load_json(os.path.splitext(a.incidents)[0] + ".json") or []
        recorded = {r.get("trial") for r in recs if isinstance(r, dict)}
    by = OrderedDict()
    for t in trials:
        by.setdefault(t["group"], []).append(t)
    L = ["# " + a.title, "",
         "Generated by `spikes/keyless/report/index.py` from " + ", ".join("`%s`" % p for p in a.paths) + ". "
         "Open a trial in Harbor's viewer with `uv run harbor view JOBS_DIR` (port 8080 by default); the "
         "Viewer links assume that. Statistics are in RESULTS.md (`summarize.py`).", ""]
    for g, ts in by.items():
        L += ["## " + g, "",
              "| Trial | Reward | Product | Honesty | First failed | Valid | Log | Trajectory | Report | Score | "
              "Grader log | Images | Incident | Viewer |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for t in ts:
            imgs = H.images(t["trial"])
            img = " ".join(link("img%d" % (i + 1), p, base) for i, p in enumerate(imgs[:3])) or "–"
            if len(imgs) > 3:
                img += " (+%d)" % (len(imgs) - 3)
            inc = "–"
            if a.incidents and t["trial_name"] in recorded:
                inc = "[%s](%s#%s)" % (t["first_failed"], os.path.relpath(os.path.abspath(a.incidents), base),
                                       anchor(t["trial_name"]))
            viewer = ("[open](%s/jobs/%s/trials/%s)" % (a.viewer.rstrip("/"), t["job_name"], t["trial_name"])
                      if t["job_name"] else "–")
            L.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                link(t["trial_name"], t["trial"], base), num(t["reward"]), num(t["product"]), num(t["honesty"]),
                t["first_failed"] or ("none" if t["at"] else "–"), "yes" if t["reward_valid"] else "**no**",
                link(os.path.basename(t["agent_log"]) if t["agent_log"] else "log", t["agent_log"], base),
                link("trajectory", t["trajectory"], base), link("report.json", t["report_path"], base),
                link("details.json", t["details_path"], base), link("grade.log", t["grade_log"], base),
                img, inc, viewer))
        L.append("")
        steps = [t for t in ts if t["at"]]
        if steps:
            L += ["Acceptance steps per trial (✓ pass, ✗ fail; the agent's claim from report.json in brackets):", "",
                  "| Trial | " + " | ".join(H.AT_STEPS) + " |", "|---|" + "---|" * len(H.AT_STEPS)]
            for t in steps:
                claims = ((t["report"] or {}).get("steps") or {}) if isinstance(t["report"], dict) else {}
                cells = []
                for i, s in enumerate(H.AT_STEPS):
                    c = claims.get(H.STEP_NAMES[i]) if isinstance(claims, dict) else None
                    cells.append(("✓" if t["at"].get(s) else "✗") + (" (%s)" % c if c else ""))
                L.append("| %s | %s |" % (t["trial_name"], " | ".join(cells)))
            L.append("")
    open(out, "w").write("\n".join(L) + "\n")
    print("wrote", out, "with", len(trials), "trials")


if __name__ == "__main__":
    main()
