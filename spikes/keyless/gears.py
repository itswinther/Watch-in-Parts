"""Gear solids for the reference and the anchors (never imported by the grader).

Involute spur gears are built as 2D polygons and extruded with manifold3d. The face
(contrate) gear is generated by envelope cutting: the mating pinion, rotated through many
synchronised angles, is subtracted from a blank.
"""
import math

import numpy as np
import manifold3d as m3


def involute_polygon(z, m, alpha_deg=25.0, add=1.0, ded=1.25, thin=0.0, n_inv=10):
    """Closed polygon of a spur gear centred at the origin, one tooth centred on +x.

    thin: amount removed from each flank, measured along the pitch circle (mm).
    """
    a = math.radians(alpha_deg)
    rp = m * z / 2.0
    rb = rp * math.cos(a)
    ra = rp + add * m
    rf = max(rp - ded * m, 0.05)
    inv = lambda t: math.tan(t) - t
    # half tooth angle on the pitch circle
    half_pitch_angle = math.pi / (2 * z) - thin / rp
    pts = []
    r_start = max(rb, rf)
    rs = np.linspace(r_start, ra, n_inv)
    pitch = 2 * math.pi / z

    def flank_angle(r):
        if r < rb:
            return half_pitch_angle + inv(a)
        ap = math.acos(min(1.0, rb / r))
        return half_pitch_angle + inv(a) - inv(ap)

    for k in range(z):
        c = k * pitch
        # root arc from previous gap centre to this tooth's lower flank start
        lower = [(r, c - flank_angle(r)) for r in rs]
        upper = [(r, c + flank_angle(r)) for r in rs[::-1]]
        g0 = c - pitch / 2
        a_root0 = c - flank_angle(r_start)
        if rf < r_start:
            pts.append((rf, g0))
            pts.append((rf, a_root0))
        else:
            pts.append((rf, g0))
        pts.extend(lower)
        pts.extend(upper)
        if rf < r_start:
            pts.append((rf, c + flank_angle(r_start)))
    xy = [(r * math.cos(t), r * math.sin(t)) for r, t in pts]
    return xy


def spur(z, m, z0, z1, thin=0.0, alpha_deg=25.0, bore=0.0, phase=0.0):
    """Spur gear along +z between z0 and z1, centred on the origin, rotated by phase (rad)."""
    poly = involute_polygon(z, m, alpha_deg, thin=thin)
    cs = m3.CrossSection([poly], m3.FillRule.Positive)
    g = m3.Manifold.extrude(cs, z1 - z0).translate([0, 0, z0])
    if bore > 0:
        g = g - m3.Manifold.cylinder(z1 - z0 + 2, bore, bore, 48).translate([0, 0, z0 - 1])
    if phase:
        g = g.rotate([0, 0, math.degrees(phase)])
    return g


def rot_axis(axis_point, axis_dir, angle):
    """4x4 rotation by angle (rad, right-hand) about the line through axis_point along axis_dir."""
    u = np.asarray(axis_dir, float)
    u = u / np.linalg.norm(u)
    c, s = math.cos(angle), math.sin(angle)
    K = np.array([[0, -u[2], u[1]], [u[2], 0, -u[0]], [-u[1], u[0], 0]])
    R = np.eye(3) + s * K + (1 - c) * K @ K
    p = np.asarray(axis_point, float)
    T = np.eye(4)
    T[:3, :3] = R
    T[:3, 3] = p - R @ p
    return T


def tf(man, T):
    return man.transform(np.asarray(T)[:3, :4].tolist())


def z_to_x(man):
    """Map a part built along +z onto +x (z->x, x->y, y->z)."""
    return man.transform([[0, 0, 1, 0], [1, 0, 0, 0], [0, 1, 0, 0]])


def pinion_along_x(z, m, x0, x1, y, zc, thin=0.0, phase=0.0):
    """Spur pinion with its axis along +x through (y, zc), from x0 to x1.

    phase rotates the pinion about +x (right-hand). At phase 0 a tooth points to +z.
    """
    g = spur(z, m, x0, x1, thin=thin)            # along z, tooth on +x of the cross-section
    g = z_to_x(g)                                 # axis -> x; the tooth that was on +x now points +y
    g = g.rotate([90.0, 0, 0])                    # rotate about x so that tooth points +z
    g = g.translate([0, y, zc])
    if phase:
        g = tf(g, rot_axis([0, y, zc], [1, 0, 0], phase))
    return g


def face_gear(zc, zp, m, centre, r_in, r_out, z_root, z_tip_plane, pinion_zc, cutter_thin=-0.0,
              steps_per_pitch=24, window_pitches=1.6):
    """Face gear on a z axis through `centre` (x, y), teeth pointing -z.

    The mating pinion has its axis along x at height pinion_zc, crossing the face gear axis,
    and sits on the -x side. The blank spans z_tip_plane..z_root (teeth) for radius r_in..r_out.
    The pinion (with teeth fattened by -cutter_thin to leave backlash) is swept and subtracted.
    Returns only the toothed ring; add the web separately.
    """
    cx, cy = centre
    ring = (m3.Manifold.cylinder(z_root - z_tip_plane, r_out, r_out, 192)
            - m3.Manifold.cylinder(z_root - z_tip_plane + 2, r_in, r_in, 192).translate([0, 0, -1]))
    ring = ring.translate([0, 0, z_tip_plane])      # crown frame: axis at the origin
    # cutter: pinion along x from -r_out-0.3 to -r_in+0.3 (wider than the ring)
    pin = pinion_along_x(zp, m, -r_out - 0.3, -r_in + 0.3, 0.0, pinion_zc, thin=cutter_thin)
    pc = 2 * math.pi / zc
    poses = []
    n = int(window_pitches * steps_per_pitch * 2) + 1
    for phi in np.linspace(-window_pitches * pc, window_pitches * pc, n):
        psi = phi * zc / zp                  # pinion turns zc/zp times as fast
        # Sense: the face gear turns +phi about +z; the pinion's tooth contact at -x, top (+z):
        # a +z rotation of the face gear moves its material at -x towards -y. The pinion top
        # moves towards -y when it turns +psi about +x (the top point (0,0,r) -> (0,-r sin, ...)).
        P = tf(pin, rot_axis([0, 0, pinion_zc], [1, 0, 0], psi))
        P = P.rotate([0, 0, -math.degrees(phi)])   # into the face gear's frame
        poses.append(P)
    cutter = m3.Manifold.batch_boolean(poses, m3.OpType.Add)
    # keep only the central gap (wedge of one pitch around the -x direction)
    R = r_out + 1
    half = pc / 2
    wedge_pts = [(0, 0)] + [(-R * math.cos(t), -R * math.sin(t)) for t in np.linspace(-half, half, 16)]
    wedge = m3.Manifold.extrude(m3.CrossSection([wedge_pts], m3.FillRule.EvenOdd), 40).translate([0, 0, -20])
    gap = cutter ^ wedge
    gaps = [gap.rotate([0, 0, math.degrees(k * pc)]) for k in range(zc)]
    allgaps = m3.Manifold.batch_boolean(gaps, m3.OpType.Add)
    teeth = ring - allgaps
    return teeth.translate([cx, cy, 0])
